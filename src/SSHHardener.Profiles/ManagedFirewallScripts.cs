    // Read-only, fail-closed recognition of this application's exact Fail2ban chains.
    // Native nftables objects must also be accounted for, including rules omitted by iptables-save.
    internal const string OwnedFirewallFunctions = """
        only_managed_fail2ban_firewall() {
          /usr/bin/python3 - <<'SSHARDENER_OWNED_FIREWALL_PY'
        import collections, hashlib, ipaddress, json, os, re, shlex, stat, subprocess, sys
        def reject():
            raise ValueError('unrecognized firewall state')
        def owned_file(path, maximum, mode=None):
            info = os.lstat(path)
            if not stat.S_ISREG(info.st_mode) or info.st_uid != 0 or info.st_mode & 0o022 or info.st_size > maximum:
                reject()
            if mode is not None and stat.S_IMODE(info.st_mode) != mode:
                reject()
            with open(path, 'rb') as source:
                return source.read(maximum + 1)
        def run(*command):
            result = subprocess.run(command, capture_output=True, text=True, timeout=5, check=True)
            if result.stderr.strip():
                reject()
            return result.stdout
        def inspect():
            base = os.lstat('/var/lib/ssh-hardener')
            if not stat.S_ISDIR(base.st_mode) or base.st_uid != 0 or stat.S_IMODE(base.st_mode) != 0o700:
                reject()
            for directory in ('/etc/fail2ban', '/etc/fail2ban/jail.d'):
                info = os.lstat(directory)
                if not stat.S_ISDIR(info.st_mode) or info.st_uid != 0 or info.st_mode & 0o022:
                    reject()
            proof = owned_file('/var/lib/ssh-hardener/fail2ban-managed.sha256', 512, 0o600).decode().split()[0]
            policy = owned_file('/etc/fail2ban/jail.d/sshhardener-sshd.local', 65536)
            if not re.fullmatch('[a-f0-9]{64}', proof) or hashlib.sha256(policy).hexdigest() != proof:
                reject()
            if not policy.startswith(b'# SSHHardener managed fail2ban jail v1\n'):
                reject()
            chain = 'f2b-sshhardener-sshd'
            expected = collections.Counter()
            nft_backends = set()
            for family, tool, saver in (('ip', 'iptables', 'iptables-save'), ('ip6', 'ip6tables', 'ip6tables-save')):
                if 'nf_tables' in run(tool, '--version'):
                    nft_backends.add(family)
                in_filter = False
                declared, jumps, returns = set(), 0, 0
                for raw in run(saver).splitlines():
                    line = raw.strip()
                    if not line or line.startswith('# Generated by ') or line.startswith('# Completed on '):
                        continue
                    if line == '*filter' and not in_filter:
                        in_filter = True
                        continue
                    if line == 'COMMIT' and in_filter:
                        in_filter = False
                        continue
                    if not in_filter:
                        reject()
                    declaration = re.fullmatch(r':(INPUT|FORWARD|OUTPUT|f2b-sshhardener-sshd) (ACCEPT|-) \[\d+:\d+\]', line)
                    if declaration:
                        name, policy_name = declaration.groups()
                        if name in declared or policy_name != ('-' if name == chain else 'ACCEPT'):
                            reject()
                        declared.add(name)
                        continue
                    words = shlex.split(line)
                    # A jump contains ten tokens; limit it to the one/two exact numeric SSH ports.
                    if len(words) == 10 and words[:7] == ['-A', 'INPUT', '-p', 'tcp', '-m', 'multiport', '--dports'] and words[8:] == ['-j', chain]:
                        ports = words[7].split(',')
                        if not 1 <= len(ports) <= 2 or any(not p.isdecimal() or not 1 <= int(p) <= 65535 for p in ports):
                            reject()
                        jumps += 1
                        if jumps > 1:
                            reject()
                        expected[(family, 'INPUT')] += 1
                    elif words == ['-A', chain, '-j', 'RETURN']:
                        returns += 1
                        if returns > 1:
                            reject()
                        expected[(family, chain)] += 1
                    elif len(words) == 8 and words[:3] == ['-A', chain, '-s'] and words[4:7] == ['-j', 'REJECT', '--reject-with']:
                        network = ipaddress.ip_network(words[3], strict=False)
                        if network.version != (4 if family == 'ip' else 6) or words[7] != ('icmp-port-unreachable' if family == 'ip' else 'icmp6-port-unreachable'):
                            reject()
                        expected[(family, chain)] += 1
                    else:
                        reject()
                if in_filter or (chain in declared and (jumps != 1 or returns != 1)) or (jumps and chain not in declared):
                    reject()
            actual = collections.Counter()
            document = json.loads(run('nft', '-j', 'list', 'ruleset'))
            for entry in document['nftables']:
                if len(entry) != 1:
                    reject()
                kind, obj = next(iter(entry.items()))
                if kind == 'metainfo':
                    continue
                if kind not in ('table', 'chain', 'rule') or obj.get('family') not in nft_backends or obj.get('table', obj.get('name')) != 'filter':
                    reject()
                if kind == 'table' and obj.get('flags'):
                    reject()
                if kind == 'chain':
                    name = obj['name']
                    if name == chain:
                        if any(key in obj for key in ('hook', 'policy', 'type')):
                            reject()
                    elif name in ('INPUT', 'FORWARD', 'OUTPUT'):
                        if obj.get('type') != 'filter' or obj.get('hook') != name.lower() or obj.get('policy') != 'accept' or obj.get('prio') not in (0, 'filter'):
                            reject()
                    else:
                        reject()
                    if obj.get('flags'):
                        reject()
                elif kind == 'rule':
                    if obj.get('chain') not in ('INPUT', chain):
                        reject()
                    actual[(obj['family'], obj['chain'])] += 1
            if actual != collections.Counter({key: count for key, count in expected.items() if key[0] in nft_backends}):
                reject()
        try:
            inspect()
        except Exception:
            sys.exit(1)
        SSHARDENER_OWNED_FIREWALL_PY
        }
        # SSHHardener managed firewall probe end

        """;
